export function spacedWindowCentres(wallLength, glazingWidth, requestedCount, doorwayWidth = 0) {
  if (
    !Number.isFinite(wallLength) ||
    wallLength <= 0 ||
    !Number.isFinite(glazingWidth) ||
    glazingWidth <= 0 ||
    !Number.isInteger(requestedCount) ||
    requestedCount < 1 ||
    !Number.isFinite(doorwayWidth) ||
    doorwayWidth < 0
  )
    throw new Error('Invalid dwelling window layout');
  const frameWidth = glazingWidth + 0.22;
  const limit = wallLength / 2 - frameWidth / 2 - 1;
  if (limit < 0) return [];
  const distribute = (low, high, count) => {
    if (high < low || count < 1) return [];
    const total = Math.min(count, Math.floor((high - low) / (frameWidth + 0.6)) + 1);
    if (total === 1) return [(low + high) / 2];
    const step = Math.max(frameWidth + 0.6, ((high - low) * 0.75) / (total - 1));
    return Array.from({ length: total }, (_, i) => (low + high) / 2 + (i - (total - 1) / 2) * step);
  };
  if (!doorwayWidth) return distribute(-limit, limit, requestedCount);
  const inner = doorwayWidth / 2 + 0.45 + frameWidth / 2;
  return [
    ...distribute(-limit, -inner, Math.floor(requestedCount / 2)),
    ...distribute(inner, limit, Math.ceil(requestedCount / 2))
  ];
}

